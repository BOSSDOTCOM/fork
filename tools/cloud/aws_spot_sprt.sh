#!/usr/bin/env bash
# One or more AWS EC2 spot instances, each running one shard of a sharded
# SPRT (docs/kb/tools.md "Cloud SPRT", branch kb). Run on the owner's own
# machine with the owner's AWS CLI configuration; the repository holds no
# credentials, account ids or bucket names.
#
#   tools/cloud/aws_spot_sprt.sh --bucket s3://BUCKET/PREFIX --instance-profile NAME \
#       --base COMMIT --test COMMIT [--games 5000] [--shards 1] [--stage 0] [--tc 8+0.08] \
#       [--hash 16] [--type c7a.16xlarge] [--region us-east-1] [--max-hours 3] \
#       [--base-opts "..."] [--test-opts "..."] [--subnet ID] [--security-group ID] [--dry-run]
#
# Each instance (Ubuntu 22.04 LTS, the TCEC toolchain's release: gcc 11.4):
#  1. arms a shutdown after --max-hours whatever happens (the cost cap);
#  2. clones the public repository, builds both commits with update.sh
#     (CXX=g++, x86-64-v3), fetches the pinned fastchess and book;
#  3. runs tools/cloud/run_shard.sh with every vCPU but two, uploading
#     result.json to S3 every minute;
#  4. watches the instance metadata (IMDSv2) for a spot interruption notice
#     and, on one, stops the shard so its finished pairs are uploaded;
#  5. uploads the log and the games, and shuts down; with
#     --instance-initiated-shutdown-behavior terminate, shutting down
#     terminates the instance.
# The instance profile (made by the owner) needs only s3:PutObject on the
# bucket's prefix. Results: aws s3 cp --recursive s3://BUCKET/PREFIX/RUN dir,
# then python3 tools/cloud/sprt_merge.py merge dir/*.json --elo0 E0 --elo1 E1.
set -euo pipefail
repo_url=https://github.com/BOSSDOTCOM/fork.git
games=5000 shards=1 stage=0 tc=8+0.08 hash=16 type=c7a.16xlarge region=${AWS_REGION:-us-east-1}
max_hours=3 base_opts="" test_opts="" subnet="" sg="" dry=0 bucket="" profile="" base="" test=""
while [ $# -gt 0 ]; do
  case $1 in
    --bucket) bucket=$2 ;; --instance-profile) profile=$2 ;; --base) base=$2 ;; --test) test=$2 ;;
    --games) games=$2 ;; --shards) shards=$2 ;; --stage) stage=$2 ;; --tc) tc=$2 ;; --hash) hash=$2 ;;
    --type) type=$2 ;; --region) region=$2 ;; --max-hours) max_hours=$2 ;; --base-opts) base_opts=$2 ;;
    --test-opts) test_opts=$2 ;; --subnet) subnet=$2 ;; --security-group) sg=$2 ;;
    --dry-run) dry=1; shift; continue ;;
    *) echo "aws_spot_sprt.sh: unknown option $1" >&2; exit 2 ;;
  esac
  shift 2
done
for v in bucket profile base test; do
  [ -n "${!v}" ] || { echo "aws_spot_sprt.sh: --${v/profile/instance-profile} is required" >&2; exit 2; }
done
case "$games$shards$stage$hash$max_hours" in *[!0-9]*) echo "numbers expected" >&2; exit 2 ;; esac
case $type in c7a.*|c8a.*) ;; *) echo "aws_spot_sprt.sh: c7a or c8a instance types only" >&2; exit 2 ;; esac
# Commits as full hashes, so every shard builds the same code.
here=$(cd "$(dirname "$0")/../.." && pwd)
base=$(git -C "$here" rev-parse --verify "$base^{commit}")
test=$(git -C "$here" rev-parse --verify "$test^{commit}")
# The scripts the instance runs come from this checkout's commit (it and the
# two commits must be pushed: the instance clones the public repository).
tools=$(git -C "$here" rev-parse HEAD)
per=$(( (games + 2 * shards - 1) / (2 * shards) * 2 ))
run=sprt-$(date -u +%Y%m%dT%H%M%SZ)-${test:0:7}-vs-${base:0:7}

user_data() {  # shard index
  cat <<EOF
#!/bin/bash
# Fork cloud SPRT shard $1 of $shards ($run), generated by tools/cloud/aws_spot_sprt.sh.
exec >/var/log/fork-shard.log 2>&1
set -uo pipefail
shutdown -h +$(( max_hours * 60 ))
upload() { aws s3 cp --only-show-errors "\$1" "${bucket%/}/$run/\$2" || true; }
export DEBIAN_FRONTEND=noninteractive HOME=/root
apt-get update -q && apt-get install -y -q build-essential cmake git python3 curl unzip awscli
git clone -q $repo_url /opt/fork
cd /opt/fork && git checkout -q $tools
CXX=g++ bash tools/cloud/build_pair.sh /opt/fork $base $test /opt/engines || { upload /var/log/fork-shard.log shard-$1.boot.log; shutdown -h now; }
bash tools/cloud/fetch_tools.sh /opt/tools || { upload /var/log/fork-shard.log shard-$1.boot.log; shutdown -h now; }
conc=\$(( \$(nproc) - 2 ))
bash tools/cloud/run_shard.sh --base /opt/engines/base/fork --test /opt/engines/test/fork \\
  --fastchess /opt/tools/fastchess --book /opt/tools/UHO_Lichess_4852_v1.epd \\
  --shard $1 --shards $shards --stage $stage --games $per --tc '$tc' --hash $hash --concurrency \$conc \\
  --base-opts '$base_opts' --test-opts '$test_opts' --out /opt/shard \\
  --meta base=$base --meta test=$test --meta runner=aws-$type --meta run=$run \\
  --checkpoint "aws s3 cp --only-show-errors /opt/shard/result.json ${bucket%/}/$run/shard-$1.json" &
shard=\$!
# Spot interruption: the notice appears at spot/instance-action about two
# minutes ahead (IMDSv2: a session token first).
( while kill -0 \$shard 2>/dev/null; do
    token=\$(curl -s -X PUT -H 'X-aws-ec2-metadata-token-ttl-seconds: 300' http://169.254.169.254/latest/api/token)
    code=\$(curl -s -o /dev/null -w '%{http_code}' -H "X-aws-ec2-metadata-token: \$token" \\
      http://169.254.169.254/latest/meta-data/spot/instance-action)
    if [ "\$code" = 200 ]; then echo "spot interruption notice"; kill -TERM \$shard; break; fi
    sleep 5
  done ) &
wait \$shard
upload /opt/shard/result.json shard-$1.json
gzip -c /opt/shard/games.pgn >/opt/shard/games.pgn.gz && upload /opt/shard/games.pgn.gz shard-$1.pgn.gz
upload /opt/shard/fastchess.log shard-$1.fastchess.log
upload /var/log/fork-shard.log shard-$1.boot.log
shutdown -h now
EOF
}

echo "run $run: $shards x $type spot, $per games each, $tc, test $test vs base $base, results ${bucket%/}/$run/"
if [ "$dry" = 1 ]; then
  echo "--- user data of shard 0 (dry run: nothing is launched)"
  user_data 0
  exit 0
fi
command -v aws >/dev/null || { echo "aws_spot_sprt.sh: the AWS CLI is not installed" >&2; exit 1; }
ami=$(aws ssm get-parameter --region "$region" --query Parameter.Value --output text \
  --name /aws/service/canonical/ubuntu/server/22.04/stable/current/amd64/hvm/ebs-gp2/ami-id)
net=()
[ -n "$subnet" ] && net+=(--subnet-id "$subnet")
[ -n "$sg" ] && net+=(--security-group-ids "$sg")
for i in $(seq 0 $(( shards - 1 ))); do
  ud=$(mktemp)
  user_data "$i" >"$ud"
  aws ec2 run-instances --region "$region" --image-id "$ami" --instance-type "$type" --count 1 \
    --instance-market-options '{"MarketType":"spot","SpotOptions":{"SpotInstanceType":"one-time","InstanceInterruptionBehavior":"terminate"}}' \
    --instance-initiated-shutdown-behavior terminate \
    --iam-instance-profile "Name=$profile" --user-data "file://$ud" "${net[@]}" \
    --tag-specifications "ResourceType=instance,Tags=[{Key=Name,Value=fork-$run-$i},{Key=fork-run,Value=$run}]" \
    --query 'Instances[0].InstanceId' --output text
  rm -f "$ud"
done
echo "launched; follow with: aws s3 ls ${bucket%/}/$run/"
